#!/usr/bin/env node
// Generates types/database.ts (Supabase "Database" shape) by introspecting a
// Postgres that has the migrations applied. Equivalent to
// `supabase gen types typescript`, usable offline and in CI.
//   DATABASE_URL=postgres://... node scripts/gen-types.mjs > types/database.ts
import pg from 'pg';

// Read-only remote mode: SUPABASE_PROJECT_REF=<ref> introspects a hosted project through the Management API's
// /database/query/read-only endpoint (SELECT-only; the caller's network layer supplies the token). Nothing is written.
const REF = process.env.SUPABASE_PROJECT_REF;
const url = process.env.DATABASE_URL ?? 'postgres://postgres@127.0.0.1:54329/ccx_test';
const db = REF ? {
  async connect() {}, async end() {},
  async query(sql) {
    const r = await fetch(`https://api.supabase.com/v1/projects/${REF}/database/query/read-only`, {
      method: 'POST', headers: { 'content-type': 'application/json', ...(process.env.SUPABASE_ACCESS_TOKEN ? { authorization: `Bearer ${process.env.SUPABASE_ACCESS_TOKEN}` } : {}) },
      body: JSON.stringify({ query: sql }) });
    if (!r.ok) throw new Error(`management API ${r.status}: ${(await r.text()).slice(0, 200)}`);
    return { rows: await r.json() };
  },
} : new pg.Client({ connectionString: url });
await db.connect();

const enums = (await db.query(`
  select t.typname as name, array_agg(e.enumlabel::text order by e.enumsortorder) as labels
    from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
   where n.nspname = 'public' group by t.typname order by 1`)).rows;
const enumNames = new Set(enums.map((e) => e.name));

const cols = (await db.query(`
  select c.relname as tbl, c.relkind as kind, a.attname as col, a.attnum,
         format_type(a.atttypid, a.atttypmod) as fmt, t.typname, t.typcategory, et.typname as elem,
         not a.attnotnull as nullable, a.atthasdef as hasdef, a.attidentity <> '' as ident, a.attgenerated <> '' as gen
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
    join pg_type t on t.oid = a.atttypid left join pg_type et on et.oid = t.typelem and t.typcategory = 'A'
   where n.nspname = 'public' and c.relkind in ('r','v','m')
   order by c.relname, a.attnum`)).rows;

const fns = (await db.query(`
  select p.proname as name, p.proretset as setof, pg_get_function_result(p.oid) as result,
         p.proargnames::text[] as argnames, p.proargmodes::text[] as argmodes, p.pronargdefaults as ndefaults,
         array(select format_type(x, null) from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) x) as argtypes,
         rt.typname as rettype, rt.typtype as rettyptype, rt.typcategory as retcat
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace join pg_type rt on rt.oid = p.prorettype
   where n.nspname = 'public' and p.prokind = 'f'
     and (has_function_privilege('authenticated', p.oid, 'execute') or has_function_privilege('service_role', p.oid, 'execute'))
   order by 1`)).rows;

function scalar(typname, fmt) {
  const base = fmt.replace(/\[\]$/, '').replace(/^public\./, '').replace(/\(.*\)$/, '');
  if (enumNames.has(base)) return `Database["public"]["Enums"]["${base}"]`;
  if (/^(smallint|integer|int2|int4|int8|bigint|numeric|real|double precision|float4|float8)/.test(base)) return 'number';
  if (/^bool/.test(base)) return 'boolean';
  if (/^json/.test(base)) return 'Json';
  if (/^(text|character|uuid|date|time|timestamp|inet|tsvector|int4range|interval|bytea|regconfig)/.test(base)) return 'string';
  return 'unknown';
}
const tsType = (fmt, typname) => (fmt.endsWith('[]') ? `${scalar(typname, fmt)}[]` : scalar(typname, fmt));

const tables = {};
for (const c of cols) (tables[c.tbl] ??= { kind: c.kind, cols: [] }).cols.push(c);

const out = [];
out.push('// AUTO-GENERATED by scripts/gen-types.mjs from the migrations. Do not edit by hand.');
out.push('export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n');
out.push('export type Database = {');
out.push('  __InternalSupabase: { PostgrestVersion: "12" };');
out.push('  public: {');
out.push('    Tables: {');
for (const [name, t] of Object.entries(tables)) {
  if (t.kind !== 'r') continue;
  out.push(`      ${name}: {`);
  out.push('        Row: {');
  for (const c of t.cols) out.push(`          ${c.col}: ${tsType(c.fmt, c.typname)}${c.nullable ? ' | null' : ''};`);
  out.push('        };');
  out.push('        Insert: {');
  for (const c of t.cols) {
    if (c.gen) { out.push(`          ${c.col}?: never;`); continue; }
    const opt = c.nullable || c.hasdef || c.ident;
    out.push(`          ${c.col}${opt ? '?' : ''}: ${tsType(c.fmt, c.typname)}${c.nullable ? ' | null' : ''};`);
  }
  out.push('        };');
  out.push('        Update: {');
  for (const c of t.cols) out.push(c.gen ? `          ${c.col}?: never;` : `          ${c.col}?: ${tsType(c.fmt, c.typname)}${c.nullable ? ' | null' : ''};`);
  out.push('        };');
  out.push('        Relationships: [];');
  out.push('      };');
}
out.push('    };');
out.push('    Views: {');
for (const [name, t] of Object.entries(tables)) {
  if (t.kind !== 'v') continue;
  out.push(`      ${name}: {`);
  out.push('        Row: {');
  for (const c of t.cols) out.push(`          ${c.col}: ${tsType(c.fmt, c.typname)} | null;`);
  out.push('        };');
  out.push('        Relationships: [];');
  out.push('      };');
}
out.push('    };');
out.push('    Functions: {');
const seen = new Set();
for (const f of fns) {
  if (seen.has(f.name)) continue;
  seen.add(f.name);
  const names = f.argnames ?? [];
  const modes = f.argmodes ?? names.map(() => 'i');
  const inArgs = [];
  const outCols = [];
  names.forEach((n, i) => {
    const m = modes[i] ?? 'i';
    if (m === 'o' || m === 't') outCols.push([n, f.argtypes[i]]);
    else inArgs.push([n, f.argtypes[i]]);
  });
  const firstDefault = inArgs.length - (f.ndefaults ?? 0);
  // A defaulted arg may be omitted (default applies) or sent as null (SQL NULL: the functions treat it as "no filter / keep").
  const args = inArgs.map(([n, ty], i) => `${n}${i >= firstDefault ? '?' : ''}: ${tsType(ty, ty)}${i >= firstDefault ? ' | null' : ''}`).join('; ');
  let ret;
  if (f.rettype === 'void') ret = 'undefined';
  else if (outCols.length) ret = `{ ${outCols.map(([n, ty]) => `${n}: ${tsType(ty, ty)}`).join('; ')} }[]`;
  else if (f.rettyptype === 'c' && tables[f.rettype]) ret = `Database["public"]["Tables"]["${f.rettype}"]["Row"]${f.setof ? '[]' : ''}`;
  else ret = `${tsType(f.rettype, f.rettype)}${f.setof ? '[]' : ''}`;
  out.push(`      ${f.name}: { Args: ${args ? `{ ${args} }` : 'Record<PropertyKey, never>'}; Returns: ${ret} };`);
}
out.push('    };');
out.push('    Enums: {');
for (const e of enums) out.push(`      ${e.name}: ${e.labels.map((l) => JSON.stringify(l)).join(' | ')};`);
out.push('    };');
out.push('    CompositeTypes: { [_ in never]: never };');
out.push('  };');
out.push('};\n');
out.push('type PublicSchema = Database["public"];');
out.push('export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"];');
out.push('export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"];');
out.push('export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"];');
out.push('export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];');
out.push('export type RpcName = keyof PublicSchema["Functions"];');
console.log(out.join('\n'));
await db.end();
