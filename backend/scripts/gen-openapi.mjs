#!/usr/bin/env node
// Generates docs/openapi.json from the App Router tree (paths, methods, auth hint, summary from the first /** */ doc comment).
//   node backend/scripts/gen-openapi.mjs > docs/openapi.json
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'app', 'api');
const files = [];
(function walk(d) { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else if (f === 'route.ts') files.push(p); } })(root);
const paths = {};
for (const f of files.sort()) {
  const src = readFileSync(f, 'utf8');
  const rel = '/api/' + relative(root, dirname(f)).replace(/\\/g, '/');
  const path = rel.replace(/\[([^\]]+)\]/g, '{$1}');
  const params = [...rel.matchAll(/\[([^\]]+)\]/g)].map((m) => ({ name: m[1], in: 'path', required: true, schema: { type: 'string' } }));
  const doc = (src.match(/\/\*\*\s*([\s\S]*?)\*\//) ?? [])[1]?.replace(/\s*\*\s?/g, ' ').trim();
  const auth = /requireAdmin/.test(src) ? 'admin' : /requireTutor/.test(src) ? 'tutor' : /requireMember/.test(src) ? 'member' : /requireUser/.test(src) ? 'user'
    : /assertCron/.test(src) ? 'cron' : /webhooks/.test(rel) ? 'webhook-signature' : 'public';
  const tag = rel.split('/')[3] ?? 'misc';
  for (const m of ['GET', 'POST', 'PUT', 'PATCH', 'DELETE']) {
    if (!new RegExp(`export (const|async function) ${m}\\b`).test(src)) continue;
    (paths[path] ??= {})[m.toLowerCase()] = {
      tags: [tag], summary: doc?.slice(0, 200) || `${m} ${path}`, parameters: params.length ? params : undefined,
      security: auth === 'public' ? [] : auth === 'cron' ? [{ cronSecret: [] }] : auth === 'webhook-signature' ? [] : [{ clerkSession: [] }],
      'x-auth': auth,
      responses: { 200: { description: 'OK — `{ data }` envelope' }, 400: { description: '`{ error: { code, message, request_id } }`' }, 401: { description: 'Sign in required' }, 403: { description: 'Forbidden' }, 429: { description: 'Rate limited' } },
    };
  }
}
console.log(JSON.stringify({
  openapi: '3.1.0',
  info: { title: '101 Codecrafts API', version: '1.1.0', description: 'Versioned REST API (/api/v1). Every response is `{ data }` or `{ error }`. Auth = Clerk session (cookie or Bearer). Generated by backend/scripts/gen-openapi.mjs.' },
  servers: [{ url: 'https://101codecrafts.com' }, { url: 'http://localhost:3000' }],
  components: { securitySchemes: { clerkSession: { type: 'http', scheme: 'bearer', description: 'Clerk session token' }, cronSecret: { type: 'http', scheme: 'bearer', description: 'CRON_SECRET' } } },
  paths,
}, null, 2));
